// Protocol designer: turns a list of message steps into a complete, runnable Phil program
// (protocol with two dual roles, one component per role, architecture and program).

export interface Step { from: "a" | "b"; name: string; type: string }
export interface ProtocolSpec { name: string; roleA: string; roleB: string; steps: Step[]; repeat: boolean }

export const STEP_TYPES = ["U8", "U32", "U64", "Bool", "String"];
const ident = (s: string, fallback: string, upper: boolean) => {
  let x = s.replace(/[^\p{L}\p{N}_]/gu, "");
  if (!/^[\p{L}_]/u.test(x)) x = fallback;
  return upper ? x[0].toUpperCase() + x.slice(1) : x[0].toLowerCase() + x.slice(1);
};

export function generateProtocol(spec: ProtocolSpec, reserved: ReadonlySet<string>): string {
  const safe = (x: string, suffix: string) => (reserved.has(x) || x === "Loop" || x === "Done" || x === "Again" ? x + suffix : x);
  const P = safe(ident(spec.name, "Chat", true), "Protocol");
  let A = safe(ident(spec.roleA, "Client", true), "Role"), B = safe(ident(spec.roleB, "Server", true), "Role");
  if (A === B) B += "2";
  if (A === P) A += "Role";
  if (B === P) B += "Role";
  const used = new Set<string>(["endpoint", "ep", "rounds", "remaining", "next", "done", "count"]);
  const steps = spec.steps.map((s, i) => {
    let name = ident(s.name, "value" + (i + 1), false);
    while (used.has(name) || reserved.has(name)) name += "_" + (i + 1);
    used.add(name);
    return { from: s.from, name, type: STEP_TYPES.includes(s.type) ? s.type : "U32" };
  });
  const session = (me: "a" | "b", tail: string) =>
    steps.map((s) => `${s.from === me ? "send" : "receive"} (${s.name} : ${s.type}) then `).join("") + tail;
  const body = (me: "a" | "b", start: string, indent: string) => {
    const lines: string[] = [];
    let ep = start;
    steps.forEach((s, i) => {
      const next = `e${i + 1}`;
      if (s.from === me) lines.push(`let ${next} = send ${s.name} on ${ep};`);
      else { lines.push(`let (${next}, ${s.name}) = receive ${s.type} on ${ep};`); lines.push(`console_write("${me === "a" ? A : B} received ${s.name} =", ${s.name});`); }
      ep = next;
    });
    return { text: lines.map((l) => indent + l).join("\n"), ep };
  };
  const sends = (me: "a" | "b") => steps.filter((s) => s.from === me);
  const params = (me: "a" | "b", extra = "") => [`endpoint : ${me === "a" ? A : B}[${P}]`, ...sends(me).map((s) => `${s.name} : ${s.type}`)].join(", ") + extra;
  const lower = (x: string) => x[0].toLowerCase() + x.slice(1);
  const clash = lower(A) === lower(B) || [A, B].some((x) => reserved.has(lower(x)) || used.has(lower(x)) || lower(x) === "chat" || lower(x) === x);
  const a = clash ? "left" : lower(A), b = clash ? "right" : lower(B);
  const out: string[] = [`// Generated by the protocol designer. Both roles are dual by construction.`];
  if (!spec.repeat) {
    out.push(`protocol ${P} {\n  role ${A} = ${session("a", "end Done")};\n  role ${B} = ${session("b", "end Done")};\n}`);
    for (const me of ["a", "b"] as const) {
      const r = body(me, "endpoint", "  ");
      out.push(`component ${me === "a" ? A : B}Worker(${params(me)}) {\n${r.text ? r.text + "\n" : ""}  close ${r.ep};\n}`);
    }
  } else {
    out.push(`protocol ${P} {\n  role ${A} = recursive Loop = select {\n    Again => ${session("a", "continue Loop")} |\n    Done => end Done\n  };\n  role ${B} = recursive Loop = offer {\n    Again => ${session("b", "continue Loop")} |\n    Done => end Done\n  };\n}`);
    const ra = body("a", "e0", "      "), rb = body("b", "ep", "        ");
    out.push(`component ${A}Worker(${params("a", ", rounds : U32")}) {\n  loop state (ep = endpoint, remaining : U32 = rounds) {\n    if eq(remaining, 0) {\n      let finished = select Done on ep;\n      close finished;\n      break;\n    } else {\n      let e0 = select Again on ep;\n${ra.text ? ra.text + "\n" : ""}      continue (${ra.ep}, remaining - 1);\n    };\n  };\n}`);
    out.push(`component ${B}Worker(${params("b")}) provides U32 {\n  let served = loop state (ep = endpoint, count : U32 = 0) {\n    offer ep {\n      Again => {\n${rb.text ? rb.text + "\n" : ""}        continue (${rb.ep}, count + 1);\n      }\n      Done => {\n        close ep;\n        break (count);\n      }\n    };\n  };\n  return served;\n}`);
  }
  const entries = steps.map((s) => `  entry ${s.name} : ${s.type};`).concat(spec.repeat ? ["  entry rounds : U32;"] : []);
  const binds = steps.map((s) => `  bind ${s.from === "a" ? a : b}.${s.name} = ${s.name};`).concat(spec.repeat ? [`  bind ${a}.rounds = rounds;`] : []);
  out.push(`architecture ${P}System {\n  instance ${a} = ${A}Worker;\n  instance ${b} = ${B}Worker;\n  process ${a}_run = ${a};\n  process ${b}_run = ${b};\n  protocol chat = ${P};\n  role chat.${A} = ${a};\n  role chat.${B} = ${b};\n${entries.join("\n")}${entries.length ? "\n" : ""}  bind ${a}.endpoint = chat.${A};\n  bind ${b}.endpoint = chat.${B};\n${binds.join("\n")}${binds.length ? "\n" : ""}}`);
  out.push(`program main = instantiate ${P}System;`);
  return out.join("\n\n") + "\n";
}

export function defaultEntry(type: string): string { return type === "Bool" ? "true" : type === "String" ? "hello" : "7"; }
