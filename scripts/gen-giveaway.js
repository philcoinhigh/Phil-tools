// Embeds the giveaway records for the site.
const fs = require("fs");
const json = (f) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch { return null; } };
const dir = "giveaway/draws";
const draws = (fs.existsSync(dir) ? fs.readdirSync(dir) : []).filter((f) => f.endsWith(".json") && !f.endsWith(".pending.json")).map((f) => json(`${dir}/${f}`)).filter(Boolean)
  .map(({ lock, draw, ...d }) => ({ ...d, lock: { ...lock, logs: undefined }, draw: { ...draw, logs: undefined } }))
  .sort((a, b) => (b.lock.time ?? 0) - (a.lock.time ?? 0));
const wasm = fs.existsSync("giveaway/phil_client.wasm") ? fs.readFileSync("giveaway/phil_client.wasm").toString("base64") : "";
fs.writeFileSync("site/src/session-data.ts", "// Generated by scripts/gen-giveaway.js. Do not edit.\n"
  + `export const CLIENT_WASM = ${JSON.stringify(wasm)};\nexport const SESSION: any = ${JSON.stringify(json("giveaway/session.json"))};\n`);
fs.writeFileSync("site/src/giveaway-data.ts", "// Generated by scripts/gen-giveaway.js. Do not edit.\n"
  + `export const PROGRAM: any = ${JSON.stringify(json("giveaway/program.json"))};\nexport const EMITTED: any = ${JSON.stringify(json("giveaway/emitted.json"))};\nexport const DRAWS: any[] = ${JSON.stringify(draws)};\n`);
