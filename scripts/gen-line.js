// Embeds The Line's records for the site.
const fs = require("fs");
const json = (f, d) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch { return d; } };
fs.writeFileSync("site/src/line-data.ts", "// Generated by scripts/gen-line.js. Do not edit.\n"
  + `export const PROGRAM: any = ${JSON.stringify(json("line/program.json", null))};\nexport const DEMO: any = ${JSON.stringify(json("line/demo.json", null))};\n`);
