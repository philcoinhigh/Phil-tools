// Embeds the on-chain sources as strings for the site.
const fs = require("fs");
const read = (f) => JSON.stringify(fs.existsSync(f) ? fs.readFileSync(f, "utf8") : "");
fs.writeFileSync("site/src/onchain-source.ts", "// Generated by scripts/gen-onchain.js. Do not edit.\n"
  + `export const PHIL = ${read("onchain/first.phil")};\nexport const LLVM = ${read("onchain/first.philc.ll")};\nexport const ENTRY = ${read("onchain/entry.c")};\n`);
