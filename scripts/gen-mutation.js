// Embeds the mutation analysis summary for the site. Published figures are aggregates: the
// per-step detail for Phil's own test goes to Phil's author first.
const fs = require("fs");
let d = null;
try { d = JSON.parse(fs.readFileSync("mutation/data.json", "utf8")); } catch {}
const pub = d && { day: d.day, philCommit: d.philCommit, philRuntimeCommit: d.philRuntimeCommit, module: d.module, generated: d.generated, malformed: d.malformed, total: d.total, server: d.server, client: d.client,
  byOperator: d.byOperator, serverByBlock: d.serverByBlock.map(({ name, mutants, oursKills }) => ({ name, mutants, oursKills })) };
fs.writeFileSync("site/src/mutation-data.ts", "// Generated by scripts/gen-mutation.js. Do not edit.\n" + `export const MUTATION: any = ${JSON.stringify(pub)};\n`);
