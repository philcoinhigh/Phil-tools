const fs = require("fs");
const esbuild = require("esbuild");
const out = esbuild.buildSync({ entryPoints: ["src/playground/main.ts"], bundle: true, minify: true, format: "iife", target: "es2020", write: false });
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const dog = fs.readFileSync("src/playground/dogmark.svg", "utf8").trim();
const html = fs.readFileSync("src/playground/template.html", "utf8").replace("__DOGMARK__", () => dog).replace("/*__BUNDLE__*/", () => js);
fs.mkdirSync("dist", { recursive: true });
fs.writeFileSync("dist/playground.html", html);
fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/index.html", html);
const ex = esbuild.buildSync({ stdin: { contents: 'export { EXAMPLES } from "./src/sim/examples";', resolveDir: ".", loader: "ts" }, bundle: true, format: "cjs", write: false });
fs.mkdirSync("out", { recursive: true });
fs.writeFileSync("out/examples.cjs", ex.outputFiles[0].text);
console.log("dist/playground.html", (html.length / 1024).toFixed(1), "KiB");
