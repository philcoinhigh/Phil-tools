// Embeds the quantum-safe vault's records for the site.
const fs = require("fs");
const json = (f, d) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch { return d; } };
fs.writeFileSync("site/src/qvault-data.ts", "// Generated by scripts/gen-qvault.js. Do not edit.\n"
  + `export const PROGRAM: any = ${JSON.stringify(json("qvault/program.json", null))};\nexport const DEMO: any = ${JSON.stringify(json("qvault/demo.json", null))};\nexport const LOCKED: any = ${JSON.stringify(json("qvault/locked.json", null))};\n`);
