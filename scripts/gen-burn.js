// Embeds the burn vault records for the site.
const fs = require("fs");
const json = (f, d) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch { return d; } };
fs.writeFileSync("site/src/burn-data.ts", "// Generated by scripts/gen-burn.js. Do not edit.\n"
  + `export const PROGRAM: any = ${JSON.stringify(json("burn/program.json", null))};\nexport const DEMO: any = ${JSON.stringify(json("burn/demo.json", null))};\nexport const VAULTS: any[] = ${JSON.stringify(json("burn/vaults.json", []))};\n`);
