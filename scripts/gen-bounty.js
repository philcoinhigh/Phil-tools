// Embeds Clip Bounties' program and its practice challenges for the site.
const fs = require("fs");
const json = (f, d) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch { return d; } };
const program = json("bounty/program.json", null);
fs.writeFileSync("site/src/bounty-data.ts", "// Generated by scripts/gen-bounty.js. Do not edit.\n"
  + `export const PROGRAM: any = ${JSON.stringify(program ? { network: "devnet", rpc: "https://api.devnet.solana.com", ...program } : null)};\nexport const DEMO: any = ${JSON.stringify(json("bounty/demo.json", null))};\n`);
